# ---------------------------------------------------------------------------
# AI Tutor
# ---------------------------------------------------------------------------

class AITutor:
    """
    Main Q-Loop AI Tutor.

    The tutor can:
    - answer quantum-algorithm questions through GPT-4o-mini and RAG
    - inspect the learner's circuit context
    - request simulation through QLoopAgent
    - explain actual simulation results
    - fall back to the local Q-Loop knowledge base if OpenAI
      is temporarily unavailable
    """

    def __init__(self) -> None:
        self.knowledge_base = KNOWLEDGE_BASE
        self.client = (
            AsyncOpenAI(api_key=settings.OPENAI_API_KEY)
            if settings.OPENAI_API_KEY
            else None
        )

    # Context formatting
    # -----------------------------------------------------------------------

    def _context_text(
        self,
        context: Optional[Dict[str, Any]],
    ) -> str:
        """
        Convert Q-Loop learner/circuit context into readable text.
        """

        if not context:
            return "No additional Q-Loop context was provided."

        lines = []

        learner_level = context.get("learner_level")
        if learner_level:
            lines.append(
                f"Learner level: {learner_level}"
            )

        lesson_id = context.get("lesson_id")
        if lesson_id:
            lines.append(
                f"Lesson: {lesson_id}"
            )

        module_id = context.get("module_id")
        if module_id:
            lines.append(
                f"Module: {module_id}"
            )

        detected_mistake = context.get("detected_mistake")
        if detected_mistake:
            lines.append(
                f"Detected mistake: {detected_mistake}"
            )

        challenge_id = context.get("challenge_id")
        if challenge_id:
            lines.append(
                f"Challenge: {challenge_id}"
            )

        # ---------------------------------------------------------------
        # Circuit context
        # ---------------------------------------------------------------

        circuit = context.get("circuit")

        if circuit:
            lines.append("")
            lines.append("Current circuit:")

            if isinstance(circuit, dict):
                qubits = circuit.get("qubits")

                if qubits is not None:
                    lines.append(
                        f"- Qubits: {qubits}"
                    )

                operations = circuit.get(
                    "operations",
                    [],
                )

                if operations:
                    for index, operation in enumerate(
                        operations,
                        start=1,
                    ):
                        if not isinstance(operation, dict):
                            lines.append(
                                f"- Operation {index}: {operation}"
                            )
                            continue

                        gate = operation.get(
                            "gate",
                            "?",
                        )

                        target = operation.get(
                            "target"
                        )

                        description = (
                            f"- {index}. {gate}"
                        )

                        if target is not None:
                            description += (
                                f" on q{target}"
                            )

                        control = operation.get(
                            "control"
                        )

                        if control is not None:
                            description += (
                                f", control q{control}"
                            )

                        control2 = operation.get(
                            "control2"
                        )

                        if control2 is not None:
                            description += (
                                f", control2 q{control2}"
                            )

                        parameter = operation.get(
                            "parameter"
                        )

                        if parameter is not None:
                            description += (
                                f", parameter={parameter}"
                            )

                        lines.append(description)

        # ---------------------------------------------------------------
        # Simulation result context
        # ---------------------------------------------------------------

        simulation_result = context.get(
            "simulation_result"
        )

        if simulation_result:
            lines.append("")
            lines.append(
                "Latest simulation result:"
            )

            if isinstance(
                simulation_result,
                dict,
            ):
                framework = simulation_result.get(
                    "framework"
                )

                if framework:
                    lines.append(
                        f"- Framework: {framework}"
                    )

                shots = simulation_result.get(
                    "shots"
                )

                if shots is not None:
                    lines.append(
                        f"- Shots: {shots}"
                    )

                depth = simulation_result.get(
                    "circuit_depth"
                )

                if depth is not None:
                    lines.append(
                        f"- Circuit depth: {depth}"
                    )

                gate_count = simulation_result.get(
                    "gate_count"
                )

                if gate_count is not None:
                    lines.append(
                        f"- Gate count: {gate_count}"
                    )

                counts = simulation_result.get(
                    "counts"
                )

                if counts:
                    lines.append(
                        "- Measurement counts:"
                    )

                    for state, count in counts.items():
                        lines.append(
                            f"  - |{state}>: {count}"
                        )

                probabilities = simulation_result.get(
                    "probabilities"
                )

                if probabilities:
                    lines.append(
                        "- Probabilities:"
                    )

                    for state, probability in (
                        probabilities.items()
                    ):
                        lines.append(
                            f"  - |{state}>: "
                            f"{float(probability) * 100:.2f}%"
                        )

        return "\n".join(lines)

    # -----------------------------------------------------------------------
    # Decide whether the agent should use a tool
    # -----------------------------------------------------------------------

    def _run_agent_if_needed(
        self,
        question: str,
        context: Optional[Dict[str, Any]] = None,
    ) -> Optional[Dict[str, Any]]:
        """
        Ask QLoopAgent whether a tool is required.

        Currently the approved tool is simulate_circuit.
        """

        try:
            analysis = agent.analyze_request(
                question,
                context,
            )

            if not analysis:
                return None

            if analysis.get("type") != "tool_required":
                return None

            tool_name = analysis.get(
                "tool"
            )

            if tool_name != "simulate_circuit":
                return None

            circuit = None

            if context:
                circuit = context.get(
                    "circuit"
                )

            if not circuit:
                return None

            return agent.run_tool(
                tool_name,
                {
                    "circuit": circuit,
                },
            )

        except Exception:
            return None

    # -----------------------------------------------------------------------
    # Circuit simulation explanation
    # -----------------------------------------------------------------------

    def _build_simulation_explanation(
        self,
        simulation_result: Dict[str, Any],
        context: Optional[Dict[str, Any]] = None,
    ) -> str:
        """
        Build an explanation from the ACTUAL Q-Loop simulation result.
        """

        if not simulation_result:
            return (
                "I could not obtain a simulation result from the "
                "Q-Loop simulator."
            )

        status = simulation_result.get(
            "status",
            "unknown",
        )

        if status != "success":
            error = simulation_result.get(
                "error"
            )

            if error:
                return (
                    "The Q-Loop simulator could not complete "
                    "the simulation.\n\n"
                    f"Error: {error}"
                )

            return (
                "The Q-Loop simulator could not complete "
                "the simulation."
            )

        lines = []

        framework = simulation_result.get(
            "framework",
            "Q-Loop simulator",
        )

        shots = simulation_result.get(
            "shots"
        )

        circuit_depth = simulation_result.get(
            "circuit_depth"
        )

        gate_count = simulation_result.get(
            "gate_count"
        )

        lines.append(
            "I ran the circuit using the Q-Loop simulator."
        )

        lines.append(
            f"Backend: {framework}"
        )

        if shots is not None:
            lines.append(
                f"Shots: {shots}"
            )

        if circuit_depth is not None:
            lines.append(
                f"Circuit depth: {circuit_depth}"
            )

        if gate_count is not None:
            lines.append(
                f"Gate count: {gate_count}"
            )

        # -------------------------------------------------------------------
        # Get the circuit that was actually simulated
        # -------------------------------------------------------------------

        circuit = simulation_result.get(
            "circuit"
        )

        if not circuit and context:
            circuit = context.get(
                "circuit"
            )

        operations = []

        if isinstance(
            circuit,
            dict,
        ):
            operations = circuit.get(
                "operations",
                [],
            ) or []

        if not operations:
            operations = simulation_result.get(
                "operations",
                [],
            ) or []

        # -------------------------------------------------------------------
        # Explain the circuit
        # -------------------------------------------------------------------

        if operations:
            lines.append("")
            lines.append(
                "Circuit explanation:"
            )

            gate_names = []

            for index, operation in enumerate(
                operations,
                start=1,
            ):
                if not isinstance(
                    operation,
                    dict,
                ):
                    continue

                gate = str(
                    operation.get(
                        "gate",
                        "",
                    )
                ).upper()

                target = operation.get(
                    "target"
                )

                control = operation.get(
                    "control"
                )

                parameter = operation.get(
                    "parameter"
                )

                gate_names.append(gate)

                if gate == "H":
                    if target is not None:
                        lines.append(
                            f"{index}. Hadamard gate on q{target}: "
                            "creates or changes superposition."
                        )
                    else:
                        lines.append(
                            f"{index}. Hadamard gate: "
                            "creates or changes superposition."
                        )

                elif gate in ("CX", "CNOT"):
                    if (
                        control is not None
                        and target is not None
                    ):
                        lines.append(
                            f"{index}. CNOT gate: q{control} "
                            f"is the control and q{target} "
                            "is the target. The target flips "
                            "when the control is |1>."
                        )
                    else:
                        lines.append(
                            f"{index}. CNOT gate: "
                            "the control qubit determines "
                            "whether the target qubit flips."
                        )

                elif gate == "X":
                    lines.append(
                        f"{index}. X gate on q{target}: "
                        "flips the computational-basis state "
                        "between |0> and |1>."
                    )

                elif gate == "Y":
                    lines.append(
                        f"{index}. Y gate on q{target}: "
                        "applies a quantum bit-flip with "
                        "a phase change."
                    )

                elif gate == "Z":
                    lines.append(
                        f"{index}. Z gate on q{target}: "
                        "changes the phase of the |1> component."
                    )

                elif gate == "S":
                    lines.append(
                        f"{index}. S gate on q{target}: "
                        "applies a phase rotation."
                    )

                elif gate == "T":
                    lines.append(
                        f"{index}. T gate on q{target}: "
                        "applies a smaller phase rotation."
                    )

                elif gate in ("SDG", "TDG"):
                    lines.append(
                        f"{index}. {gate} gate on q{target}: "
                        "applies the corresponding inverse "
                        "phase operation."
                    )

                elif gate == "SWAP":
                    lines.append(
                        f"{index}. SWAP gate: "
                        "exchanges the quantum states "
                        "of the configured qubits."
                    )

                elif gate in ("M", "MEASURE"):
                    lines.append(
                        f"{index}. Measurement on q{target}: "
                        "converts the quantum state into "
                        "a classical measurement result."
                    )

                elif gate in ("RX", "RY", "RZ"):
                    if parameter is not None:
                        lines.append(
                            f"{index}. {gate} rotation on q{target} "
                            f"with parameter {parameter}."
                        )
                    else:
                        lines.append(
                            f"{index}. {gate} rotation on q{target}."
                        )

                elif gate in ("P", "U"):
                    if parameter is not None:
                        lines.append(
                            f"{index}. {gate} gate on q{target} "
                            f"with parameter {parameter}."
                        )
                    else:
                        lines.append(
                            f"{index}. {gate} gate on q{target}."
                        )

                elif gate in (
                    "TOFFOLI",
                    "CCX",
                ):
                    lines.append(
                        f"{index}. {gate} gate: "
                        "uses two control qubits and "
                        "one target qubit."
                    )

                elif gate:
                    lines.append(
                        f"{index}. {gate} gate "
                        f"on q{target}."
                    )

            # ---------------------------------------------------------------
            # Bell-state recognition
            # ---------------------------------------------------------------

            normalized_gates = [
                gate
                for gate in gate_names
                if gate
            ]

            if (
                len(normalized_gates) >= 2
                and normalized_gates[0] == "H"
                and normalized_gates[1]
                in ("CX", "CNOT")
            ):
                lines.append("")
                lines.append(
                    "This circuit has the structure of a "
                    "Bell-state circuit."
                )

                lines.append(
                    "The Hadamard gate first creates "
                    "superposition on the first qubit."
                )

                lines.append(
                    "The CNOT then correlates the two qubits, "
                    "creating entanglement."
                )

                lines.append(
                    "Ideally, measuring this state produces "
                    "correlated outcomes such as |00> and |11>."
                )

        # -------------------------------------------------------------------
        # Actual measurement results
        # -------------------------------------------------------------------

        counts = simulation_result.get(
            "counts"
        )

        if counts:
            lines.append("")
            lines.append(
                "Actual measurement results:"
            )

            total_counts = sum(
                int(value)
                for value in counts.values()
            )

            for state, count in counts.items():
                count_value = int(count)

                if total_counts > 0:
                    percentage = (
                        count_value
                        / total_counts
                        * 100
                    )
                else:
                    percentage = 0

                lines.append(
                    f"- |{state}>: "
                    f"{count_value} shots "
                    f"({percentage:.2f}%)"
                )

            lines.append("")
            lines.append(
                "These measurement values come from the "
                "actual Q-Loop simulator execution."
            )

        # -------------------------------------------------------------------
        # Probability results
        # -------------------------------------------------------------------

        probabilities = simulation_result.get(
            "probabilities"
        )

        if probabilities:
            lines.append("")
            lines.append(
                "Calculated probabilities:"
            )

            for state, probability in (
                probabilities.items()
            ):
                try:
                    percentage = (
                        float(probability)
                        * 100
                    )
                except (
                    TypeError,
                    ValueError,
                ):
                    continue

                lines.append(
                    f"- |{state}>: "
                    f"{percentage:.2f}%"
                )

        return "\n".join(lines)

    # -----------------------------------------------------------------------
    # Normal fallback explanation
    # -----------------------------------------------------------------------

    def _fallback_explanation(
        self,
        question: str,
        context: Optional[Dict[str, Any]] = None,
    ) -> str:
        """
        Answer common quantum-algorithm questions locally.

        This is NOT an external AI model. It is only a safety fallback
        when OpenAI or RAG is unavailable.
        """

        question_lower = question.lower()

        # ---------------------------------------------------------------
        # Direct knowledge-base matching
        # ---------------------------------------------------------------

        for topic, explanation in (
            self.knowledge_base.items()
        ):
            if topic in question_lower:
                return explanation

        # ---------------------------------------------------------------
        # More specific keyword handling
        # ---------------------------------------------------------------

        if "what is a quantum algorithm" in question_lower:
            return (
                "A quantum algorithm is a step-by-step procedure "
                "designed to solve a problem using quantum operations "
                "such as superposition, interference, entanglement, "
                "quantum gates, and measurement."
            )

        if "quantum algorithm" in question_lower:
            return (
                "A quantum algorithm is a sequence of quantum "
                "operations designed to solve a computational problem. "
                "It can use concepts such as superposition, "
                "entanglement, interference, and measurement."
            )

        if "hadamard" in question_lower:
            return self.knowledge_base[
                "hadamard"
            ]

        if "cnot" in question_lower:
            return self.knowledge_base[
                "cnot"
            ]

        if "bell state" in question_lower:
            return self.knowledge_base[
                "bell"
            ]

        if "entangle" in question_lower:
            return self.knowledge_base[
                "entanglement"
            ]

        if "measure" in question_lower:
            return self.knowledge_base[
                "measurement"
            ]

        if "superposition" in question_lower:
            return self.knowledge_base[
                "superposition"
            ]

        if "qubit" in question_lower:
            return self.knowledge_base[
                "qubit"
            ]

        # ---------------------------------------------------------------
        # Circuit-aware generic response
        # ---------------------------------------------------------------

        if context and context.get(
            "circuit"
        ):
            circuit = context.get(
                "circuit"
            )

            if isinstance(
                circuit,
                dict,
            ):
                operations = circuit.get(
                    "operations",
                    [],
                )

                if operations:
                    return (
                        "I can analyze your current Q-Loop circuit. "
                        "Ask me to simulate it, explain the gates, "
                        "or explain why the measurement results occur."
                    )

        return (
            "I can help you learn quantum algorithms, quantum gates, "
            "circuits, superposition, entanglement, measurement, "
            "and simulation results. "
            "Try asking a specific question such as "
            "'What does the Hadamard gate do?'"
        )

    # -----------------------------------------------------------------------
    # Main GPT-4o-mini + RAG tutor
    # -----------------------------------------------------------------------

    async def explain(
        self,
        question: str,
        context: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        question = (question or "").strip()
        context = context or {}

        if not question:
            return {
                "response": "Please ask a quantum-computing or quantum-algorithm question.",
                "suggestions": ["Explain superposition", "Explain Grover's algorithm", "What does the Hadamard gate do?"],
                "code_example": None,
                "confidence": "high",
                "sources": ["Q-Loop AI Tutor"],
            }

        # Preserve the simulator as a deterministic Q-Loop tool. GPT does not
        # invent circuit execution results.
        simulation_result = self._run_agent_if_needed(question, context)
        if simulation_result:
            return {
                "response": self._build_simulation_explanation(simulation_result, context),
                "suggestions": [
                    "Explain the gates step by step",
                    "Why are these measurement results obtained?",
                    "Explain this circuit like a beginner",
                ],
                "code_example": None,
                "confidence": "high",
                "sources": ["Q-Loop Simulator"],
            }

        retrieved = []
        if self.client:
            try:
                retrieved = await retrieve_relevant_chunks(question)
            except Exception as exc:
                print(f"[rag] Retrieval failed: {exc}")

            context_text = self._context_text(context)
            source_blocks = []
            source_labels = []
            for index, item in enumerate(retrieved, start=1):
                location = " · ".join(
                    str(value) for value in (
                        item.get("chapter"),
                        item.get("section"),
                        f"page {item.get('page')}" if item.get("page") else None,
                    ) if value
                )
                label = str(item.get("source_name") or "Q-Loop knowledge base")
                if location:
                    label += f" · {location}"
                source_labels.append(label)
                source_blocks.append(f"[{index}] {label}\n{item.get('content', '')}")

            knowledge_context = (
                "\n\n".join(source_blocks)
                if source_blocks
                else "No matching indexed source was found for this question."
            )

            system_prompt = (
                "You are Q-Loop's quantum computing and quantum algorithm tutor. "
                "Teach clearly in beginner-friendly English, using correct mathematics and examples. "
                "Use the retrieved Q-Loop sources as the primary authority. "
                "When a claim comes from a retrieved source, cite it using its bracket number, such as [1]. "
                "Never invent a book title, page number, module, section, or source. "
                "If the retrieved sources do not contain the answer, say so clearly and distinguish any "
                "general background knowledge from Q-Loop course material. "
                "Use the learner and circuit context only when relevant. Never claim to have run a circuit; "
                "the Q-Loop simulator is the only source of actual simulation results."
            )
            user_prompt = (
                f"Question:\n{question}\n\n"
                f"Learner and circuit context:\n{context_text}\n\n"
                f"Retrieved knowledge:\n{knowledge_context}\n\n"
                "Answer with a clear explanation, steps or an example when useful."
            )

            try:
                completion = await self.client.chat.completions.create(
                    model=settings.OPENAI_MODEL,
                    messages=[
                        {"role": "system", "content": system_prompt},
                        {"role": "user", "content": user_prompt},
                    ],
                    temperature=0.2,
                    max_tokens=1100,
                )
                answer = (completion.choices[0].message.content or "").strip()
                if answer:
                    return {
                        "response": answer,
                        "suggestions": [
                            "Explain it more simply",
                            "Give me a worked example",
                            "Show how this relates to a quantum circuit",
                        ],
                        "code_example": None,
                        "confidence": "high" if retrieved else "medium",
                        "sources": source_labels or ["GPT-4o-mini general knowledge"],
                    }
            except Exception as exc:
                print(f"[ai] GPT-4o-mini request failed: {exc}")

        return {
            "response": self._fallback_explanation(question, context),
            "suggestions": [
                "Explain this with an example",
                "Show me a quantum circuit",
                "Explain it step by step",
            ],
            "code_example": None,
            "confidence": "medium",
            "sources": ["Q-Loop local knowledge base"],
        }

    async def hint(self, question: str, context: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
        return await self.explain(
            "Give me one helpful hint without revealing the complete solution. " + question,
            context,
        )

    async def debug(self, question: str, context: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
        return await self.explain(
            "Help me debug this quantum circuit or code issue. Identify likely cause and safe next checks. " + question,
            context,
        )

    async def optimize(self, question: str, context: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
        return await self.explain(
            "Suggest valid improvements for this quantum circuit or code. Explain trade-offs and do not claim unverified execution. " + question,
            context,
        )

    async def generate_code(self, question: str, context: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
        result = await self.explain(
            "Provide a small, correct quantum programming example, preferably Qiskit unless another framework is requested. Include the code in a fenced Python code block. " + question,
            context,
        )
        match = re.search(r"```(?:python)?\s*([\s\S]*?)```", result.get("response", ""))
        if match:
            result["code_example"] = match.group(1).strip()
        return result


